def parse_admins(raw: str) -> tuple[int, ...]:
    """Parse a comma-separated list of admin user ids into ints."""
    out = []
    for part in str(raw or "").split(","):
        part = part.strip()
        if part.isdigit():
            out.append(int(part))
    return tuple(out)



def check_python_version() -> None:
    """Fail fast below Python 3.11; warn (never crash) on 3.12+."""
    if sys.version_info < (3, 11):
        print(
            "ERROR: Python 3.11.9 is required (found "
            + platform.python_version()
            + "). On Termux run: pkg install python3.11"
        )
        raise SystemExit(1)
    if sys.version_info >= (3, 12):
        print(
            "WARNING: Python 3.12+ detected. This bot targets "
            + TARGET_PYTHON
            + "; pinned dependencies are tested on 3.11."
        )


def require_bot_token() -> str:
    """Return BOT_TOKEN or exit(1) with a clear message (Section 32)."""
    token = os.environ.get("BOT_TOKEN", "").strip()
    if not token:
        print(
            "ERROR: BOT_TOKEN is not set. Copy .env.example to .env and paste "
            "the token from @BotFather, then start the bot again."
        )
        raise SystemExit(1)
    return token


def check_required_env(report_missing: bool = True) -> list[str]:
    """Return the list of required env vars that are missing."""
    missing = [name for name in REQUIRED_ENV_NAMES if not os.environ.get(name, "").strip()]
    if missing and report_missing:
        print("ERROR: required environment variables are missing: " + ", ".join(missing))
    return missing


def _scrub(record) -> bool:
    """loguru filter: remove secret values from every log record (Section 27)."""
    message = record["message"]
    for name in SECRET_ENV_NAMES:
        value = os.environ.get(name, "")
        if value and value in message:
            message = message.replace(value, "***")
    record["message"] = message
    return True


def setup_logging() -> None:
    """Configure loguru with secret scrubbing and the chosen level."""
    from loguru import logger

    logger.remove()
    logger.add(
        sys.stderr,
        level=LOG_LEVEL,
        filter=_scrub,
        format="{time:YYYY-MM-DD HH:mm:ss} | {level: <8} | {name}:{line} | {message}",
    )
    logger.add(
        str(DATA_DIR / "bot.log"),
        level=LOG_LEVEL,
        filter=_scrub,
        rotation="5 MB",
        retention=3,
        encoding="utf-8",
    )
